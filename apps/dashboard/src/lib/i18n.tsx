export type Lang = 'ar' | 'en';
export type MessageKey = keyof typeof ar;
export const messages: Record<Lang, Record<MessageKey, string>> = { ar, en };

interface I18n {
  lang: Lang;
  rtl: boolean;
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
  toggle: () => void;
}

const Ctx = createContext<I18n | null>(null);
const STORE_KEY = 'naql.lang';

function initialLang(): Lang {
  try {
    return localStorage.getItem(STORE_KEY) === 'en' ? 'en' : 'ar';
  } catch {
    return 'ar';
  }
}

/** Arabic RTL by default (ST-12 applies to the dashboard too). */
export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initialLang);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    try {
      localStorage.setItem(STORE_KEY, lang);
    } catch {
      /* private mode */
    }
  }, [lang]);
  const value: I18n = { lang, rtl: lang === 'ar', t: (k, vars) => (vars ? messages[lang][k].replace(/\{(\w+)\}/g, (m, n) => (n in vars ? String(vars[n]) : m)) : messages[lang][k]), toggle: () => setLang((l) => (l === 'ar' ? 'en' : 'ar')) };
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside I18nProvider');
  return v;
}

/** IQD amounts with Western digits and grouping (as on Iraqi receipts), unit in the active language. */
export function useMoney() {
  const { t } = useI18n();
  return (n: number) => `${n.toLocaleString('en-US')} ${t('tiers.iqd')}`;
}
